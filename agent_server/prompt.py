def _load_json(name):
    with open(os.path.join(BRAND_DIR, name), encoding="utf-8") as f:
        return json.load(f)


def load_tools():
    """OpenAI tools 파라미터 형식으로 변환한 함수 정의 목록."""
    tools = _load_json("tools.json")
    return [{"type": "function", "function": t} for t in tools]


def build_system_prompt():
    style = _load_json("style.json")
    info = _load_json("information.json")
    with open(os.path.join(BRAND_DIR, "scenarios.md"), encoding="utf-8") as f:
        scenarios = f.read()

    info_text = "\n".join(f"- [{x['tag']}] {x['content']}" for x in info)

    return f"""\
당신은 건강기능식품 쇼핑몰 "하루온" 고객센터의 전화 상담 AI입니다. 아래 자료만을 근거로 응대하세요.

## 첫 인사
"{style['greeting']}"

## 말투 규칙
{style['style']}

{RESPONSE_STYLE}

{TOOL_CALL_RULES}

## 상담 시나리오
{scenarios}

## 브랜드 정보 (사실관계 근거)
{info_text}

{HANDOFF_POLICY}
"""
